-- Schema v26: cloud-managed accounts running on a local installation.
-- See 026_cloud_accounts.sql for the data model notes.

ALTER TABLE users ADD COLUMN IF NOT EXISTS source TEXT NOT NULL DEFAULT 'local';
ALTER TABLE users ADD COLUMN IF NOT EXISTS cloud_issuer TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS cloud_subject TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS cloud_synced_at BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_cloud_identity
  ON users(cloud_issuer, cloud_subject)
  WHERE cloud_subject IS NOT NULL;

CREATE TABLE IF NOT EXISTS cloud_sessions (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id        TEXT NOT NULL UNIQUE,
  user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  refresh_token_enc BYTEA,
  device_label      TEXT,
  cloud_expires_at  BIGINT NOT NULL DEFAULT 0,
  grace_expires_at  BIGINT NOT NULL DEFAULT 0,
  revoked_at        BIGINT,
  created_at        BIGINT NOT NULL,
  last_seen_at      BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cloud_sessions_user
  ON cloud_sessions(user_id);

CREATE INDEX IF NOT EXISTS idx_cloud_sessions_grace
  ON cloud_sessions(grace_expires_at);
